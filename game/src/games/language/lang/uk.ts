import type { LangCode } from '@/core/lang';
import type { LanguageTexts, PackView } from './types';

/** The Language galaxy in Ukrainian. */

/** «англійські літери», «англійську літеру», «англійське слово», «англійського слова», «англійських слів», «англійська абетка» */
const ADJECTIVE: Record<LangCode, [string, string, string, string, string, string]> = {
  uk: ['українські', 'українську', 'українське', 'українського', 'українських', 'українська'],
  en: ['англійські', 'англійську', 'англійське', 'англійського', 'англійських', 'англійська'],
  pl: ['польські', 'польську', 'польське', 'польського', 'польських', 'польська'],
};
/** The adjective with a space after it for a foreign pack, nothing for the child's own language. */
const of = (p: PackView, form: 0 | 1 | 2 | 3 | 4 | 5) => (p.native ? '' : `${ADJECTIVE[p.lang][form]} `);
const foreign = (p: PackView, form: 0 | 1 | 2 | 3 | 4) => ADJECTIVE[p.lang][form];
const whole = (p: PackView) => (p.syllables ? 'зі складів' : 'з літер');

export const uk: LanguageTexts = {
  title: 'Мова',
  packName: (lang) => ({ uk: 'Українська мова', en: 'Англійська мова', pl: 'Польська мова' })[lang],
  card: () => undefined,
  stage: (at, p) => {
    switch (at) {
      case 'abcPlain':
        return 'Тепер у порожніх клітинках немає підказок. Згадай, яка літера за якою стоїть!';
      case 'abcLong':
        return 'Таблиця стала більшою: тепер у ній три рядки літер.';
      case 'abcSpot':
        return 'Тепер усі літери на місці — але дві з них помінялися місцями. Знайди й торкнись однієї з них!';
      case 'abcWhole':
        return `Перед тобою вся ${of(p, 5)}абетка! Постав на місця всі літери, яких бракує.`;
      case 'parts':
        if (p.native) return 'Тепер у бульбашках — склади. Лопай їх по порядку, щоб вийшло слово!';
        return p.syllables
          ? `Тепер збираємо ${foreign(p, 0)} слова зі складів. Лопай склади так, як вони стоять у слові!`
          : `Тепер збираємо короткі ${foreign(p, 0)} слова. Лопай літери так, як вони стоять у слові!`;
      case 'spell':
        return p.native ? 'А тепер складаємо слова з окремих літер. Лопай літеру за літерою!' : 'Слова стають довшими. Лопай літеру за літерою — зліва направо!';
      case 'strays':
        return p.byEar
          ? 'Тепер слово не написане — послухай його і склади сам. Обережно: серед бульбашок є зайві літери!'
          : 'Обережно: серед бульбашок тепер є зайві літери. Вони не лопаються!';
      case 'sameLetter':
        return 'Тепер з’єднуємо два слова, які починаються на однакову літеру.';
      case 'halves':
        return 'Слово розпалося на дві половинки! Знайди для кожного початку його закінчення.';
      case 'assoc':
        return 'Тепер шукаємо слова, пов’язані за змістом: що з чим буває разом?';
      case 'three':
        return 'Речення стають довшими: тепер у них три слова.';
      case 'long':
        return 'А тепер — справжні великі речення з чотирьох і п’яти слів!';
    }
  },

  order: (a, b) => `В абетці літера «${a}» стоїть раніше, ніж літера «${b}».`,
  swapAsk: (p) => `Дві ${of(p, 0)}літери помінялися місцями. Торкнись літери, яка стоїть не на своєму місці.`,
  swapHint: (p, order) => (p.native ? `${order} Ці дві літери блимають.` : `Проспівай ${foreign(p, 1)} абетку по порядку. Дві літери, що помінялися місцями, блимають.`),
  after: (prev, letter) => `Після літери «${prev}» в абетці стоїть літера «${letter}».`,
  before: (next, letter) => `Перед літерою «${next}» в абетці стоїть літера «${letter}».`,
  fillAsk: (p, how) =>
    how === 'all'
      ? `Склади всю ${of(p, 1)}абетку: постав кожну літеру на її місце.`
      : how === 'one'
        ? `Постав ${of(p, 1)}літеру на її місце в абетці.`
        : `Постав ${of(p, 0)}літери на свої місця в абетці.`,
  fillHint: (p, neighbour) =>
    p.native ? `${neighbour} Її місце блимає.` : `Згадай ${foreign(p, 1)} абетку. Місце для наступної літери блимає, а в порожніх клітинках видно підказки.`,

  runAsk: (p, from, to) => (p.native ? `Лопай літери за абеткою: від ${from} до ${to}.` : `Лопай ${foreign(p, 0)} літери за абеткою — від першої до останньої.`),
  runHint: (p, letters) => (p.native ? `Згадай абетку: ${letters.join(', ')}.` : `Згадай ${foreign(p, 1)} абетку. Потрібна бульбашка блимає.`),
  partsAsk: (p, word) => (p.native ? `Збери слово зі складів: ${word}.` : `Збери ${foreign(p, 2)} слово ${whole(p)}. Воно написане під малюнком.`),
  partsHint: (p, word, parts) =>
    p.native ? `Слово «${word}» складається так: ${parts.join(' — ')}.` : `Подивись на слово під малюнком і лопай ${p.syllables ? 'склади' : 'літери'} зліва направо.`,
  spellAsk: (p, word, byEar) => {
    if (p.native) return byEar ? 'Послухай слово і склади його з літер.' : `Склади слово з літер: ${word}.`;
    return byEar ? `Послухай ${foreign(p, 2)} слово і склади його з літер.` : `Склади ${foreign(p, 2)} слово з літер. Воно написане під малюнком.`;
  },
  spellHint: (p, word, letters, byEar) => {
    if (p.native) return `Вимов слово повільно: ${word}. Його літери: ${letters.join(', ')}.`;
    return byEar
      ? 'Натисни на динамік біля малюнка, послухай слово ще раз і лопай літери зліва направо. Зайві літери не лопаються.'
      : 'Подивись на слово під малюнком і лопай літери зліва направо. Зайві літери не лопаються.';
  },

  firstAsk: (p) => (p.native ? 'З’єднай кожне слово з літерою, на яку воно починається.' : `З’єднай кожне ${foreign(p, 2)} слово з його першою літерою.`),
  firstHint: (p, word, letter) =>
    p.native ? `Вимов слово вголос і послухай перший звук. «${word}» починається на літеру «${letter}».` : 'Подивись, з якої літери починається кожне слово.',
  sameAsk: (p) => `З’єднай ${of(p, 0)}слова, які починаються на однакову літеру.`,
  sameHint: (p, a, b, letter) => (p.native ? `«${a}» і «${b}» починаються на однакову літеру — «${letter}».` : 'Порівняй перші літери слів: у пари вони однакові.'),
  halfAsk: (p) => `З’єднай початок ${of(p, 3)}слова з його закінченням.`,
  halfHint: (p, head, tail) =>
    p.native ? `Подивись на малюнок: це «${head}${tail}». Слово починається зі складу «${head}».` : 'Натисни на динамік біля малюнка, послухай слово і знайди його початок.',
  assocAsk: (p) => `З’єднай ${of(p, 0)}слова, які пов’язані за змістом.`,
  assocHint: (p, a, b) => (p.native ? `Подумай, що буває разом. «${a}» — «${b}».` : 'Натисни на динамік, щоб почути слово. Шукай те, що буває з ним разом.'),

  rhymeAsk: (p) => `Знайди пари ${of(p, 4)}слів, які римуються.`,
  rhymeHint: (p, a, b) =>
    p.native ? `Слова римуються, коли закінчуються однаково: «${a}» — «${b}».` : 'Натисни на динаміки й послухай: слова, що римуються, звучать наприкінці однаково.',
  rhymeYes: (a, b) => `«${a}» — «${b}». Це рима!`,

  sentenceAsk: (p) => `Постав ${of(p, 0)}слова по порядку, щоб вийшло речення.`,
  sentenceHint: (p, first) =>
    p.native ? `Речення починається зі слова з великої літери: «${first}». Останнє слово — з крапкою.` : 'Речення починається зі слова з великої літери, а закінчується словом із крапкою.',
  ends: ['початок', 'кінець'],
};
