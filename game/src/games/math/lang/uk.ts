function heaps(n: number): string {
  const ones = n % 10;
  const tens = n % 100;
  if (ones === 1 && tens !== 11) return `${num(n, 'f')} купка`;
  return ones >= 2 && ones <= 4 && !(tens >= 12 && tens <= 14) ? `${num(n, 'f')} однакові купки` : `${num(n, 'f')} однакових купок`;
}

