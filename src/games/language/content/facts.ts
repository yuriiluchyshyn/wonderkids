/** A pack's own facts with the extra ones added, group by group. */
export function withMoreFacts(own: Record<Group, string[]>, more: Record<Group, string[]>): Record<Group, string[]> {
  return Object.fromEntries((Object.keys(own) as Group[]).map((group) => [group, [...new Set([...own[group], ...more[group]])]])) as Record<Group, string[]>;
}
