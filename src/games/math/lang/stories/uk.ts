function form(n: number, item: Item): string {
  const ones = n % 10;
  const tens = n % 100;
  if (ones === 1 && tens !== 11) return item.one;
  return ones >= 2 && ones <= 4 && !(tens >= 12 && tens <= 14) ? item.few : item.many;
}

