const rule = (r: Rule): string => {
  switch (r.kind) {
    case 'add':
      return `щоразу додається ${N(r.by)}`;
    case 'sub':
      return `щоразу віднімається ${N(r.by)}`;
    case 'alt':
      return `додається то ${N(r.by)}, то ${N(r.then)} — по черзі`;
    case 'double':
      return 'кожне число вдвічі більше за попереднє';
    case 'triple':
      return 'кожне число втричі більше за попереднє';
    case 'half':
      return 'кожне число вдвічі менше за попереднє';
    case 'grow':
      return 'спочатку додається один, потім два, потім три, а далі — чотири';
    case 'shrink':
      return 'спочатку віднімається один, потім два, потім три, а далі — чотири';
    case 'two':
      return 'тут переплелися два ряди — дивись через одне число';
  }
};

